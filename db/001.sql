CREATE TABLE items(id INTEGER PRIMARY KEY,kind TEXT NOT NULL,title TEXT NOT NULL,date TEXT NOT NULL,goal INTEGER REFERENCES items ON DELETE SET NULL,plan INTEGER REFERENCES items ON DELETE SET NULL,task INTEGER REFERENCES items ON DELETE SET NULL,data TEXT NOT NULL);
CREATE INDEX by_date ON items(date,kind);
CREATE TABLE marks(item INTEGER REFERENCES items ON DELETE CASCADE,day TEXT,value TEXT,PRIMARY KEY(item,day));
CREATE TABLE files(id INTEGER PRIMARY KEY,item INTEGER REFERENCES items ON DELETE CASCADE,name TEXT,bytes BLOB);
CREATE TABLE prefs(key TEXT PRIMARY KEY,value TEXT);
CREATE TABLE notices(item INTEGER REFERENCES items ON DELETE CASCADE,stamp TEXT,PRIMARY KEY(item,stamp));
CREATE TABLE history(item INTEGER REFERENCES items ON DELETE CASCADE,stamp TEXT,value INTEGER);
PRAGMA user_version=1;
